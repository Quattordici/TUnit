using System.Globalization;
using System.Net;
using System.Text;

namespace TUnit.Engine.Reporters.History;

/// <summary>
/// Renders a <see cref="TrendReport"/> as one self-contained HTML page: inline CSS and
/// server-rendered SVG charts, no scripts, so it works offline and as a CI artifact.
/// </summary>
internal static class TrendsHtmlGenerator
{
    internal const int TableRows = 15;

    private const int ChartWidth = 760;
    private const int ChartHeight = 200;
    private const int PadLeft = 52;
    private const int PadRight = 12;
    private const int PadTop = 14;
    private const int PadBottom = 26;

    internal static string Generate(TrendReport report)
    {
        var sb = new StringBuilder();
        sb.Append("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
          .Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
          .Append("<title>Test Trends</title>\n<style>").Append(Css).Append("</style>\n</head>\n<body>\n<main>\n")
          .Append("<header><div class=\"eyebrow\">TUnit</div><h1>Test trends</h1>\n");

        if (report.Latest is not { } latest)
        {
            sb.Append("<p class=\"muted\">No runs in history yet. Append a run with <code>tunit-report history append</code>.</p>\n</header>\n");
        }
        else
        {
            var context = new RenderContext(report, report.Tests.Select(static t => t.Suite).Distinct().Count() > 1);
            AppendSubtitle(sb, report, latest);
            sb.Append("</header>\n");
            AppendTiles(sb, report, latest);
            AppendResultsChart(sb, report.Runs);
            AppendDurationChart(sb, report.Runs);
            AppendTestSections(sb, context);
            AppendRecentRuns(sb, report.Runs, context);
        }

        sb.Append("<footer class=\"muted\">Generated by <code>tunit-report trends</code>.</footer>\n</main>\n</body>\n</html>\n");
        return sb.ToString();
    }

    private sealed record RenderContext(TrendReport Report, bool ShowSuites);

    private static void AppendSubtitle(StringBuilder sb, TrendReport report, RunRecord latest)
    {
        sb.Append("<p class=\"muted\">").Append(Encode(TrendFormat.Count(report.Runs.Count, "run", "runs")))
          .Append(" from ").Append(Encode(TrendFormat.Date(report.Runs[0].Timestamp)))
          .Append(" to ").Append(Encode(TrendFormat.Date(latest.Timestamp)));
        if (report.Options.Branch is { } branch)
        {
            sb.Append(" on <strong>").Append(Encode(branch)).Append("</strong>");
        }
        sb.Append("</p>\n");
    }

    private static void AppendTiles(StringBuilder sb, TrendReport report, RunRecord latest)
    {
        var previous = report.Previous;
        sb.Append("<section class=\"tiles\">\n");

        AppendTile(sb, "Pass rate", latest.Counts.PassRate is { } rate ? TrendFormat.Percent(rate) : "n/a",
            report.PassRateChange is { } change ? (TrendFormat.PointsChange(change), Tone(change)) : null);
        AppendTile(sb, "Duration", TrendFormat.Duration(latest.DurationMs),
            previous is null ? null : (TrendFormat.DurationChange(latest.DurationMs - previous.DurationMs), Tone(previous.DurationMs - latest.DurationMs)));
        AppendTile(sb, "Tests", latest.Counts.Total.ToString(CultureInfo.InvariantCulture),
            previous is null ? null : (TrendFormat.CountChange(latest.Counts.Total - previous.Counts.Total), "neutral"));
        AppendTile(sb, "Failed", latest.Counts.Failed.ToString(CultureInfo.InvariantCulture),
            previous is null ? null : (TrendFormat.CountChange(latest.Counts.Failed - previous.Counts.Failed), Tone(previous.Counts.Failed - latest.Counts.Failed)));
        AppendTile(sb, "Newly failing", report.NewlyFailing().Count.ToString(CultureInfo.InvariantCulture), null);
        AppendTile(sb, "Flaky tests", report.Flakiest(int.MaxValue).Count.ToString(CultureInfo.InvariantCulture), null);

        sb.Append("</section>\n");
    }

    // Positive = better. Tiny changes stay neutral so rounding noise isn't colored.
    private static string Tone(double improvement) => improvement switch
    {
        > 1e-9 => "good",
        < -1e-9 => "bad",
        _ => "neutral",
    };

    private static void AppendTile(StringBuilder sb, string label, string value, (string Text, string Tone)? delta)
    {
        sb.Append("<div class=\"tile\"><div class=\"label\">").Append(Encode(label))
          .Append("</div><div class=\"value\">").Append(Encode(value)).Append("</div>");
        if (delta is { } d)
        {
            sb.Append("<div class=\"delta ").Append(d.Tone).Append("\">").Append(Encode(d.Text)).Append(" vs previous</div>");
        }
        sb.Append("</div>\n");
    }

    private static void AppendResultsChart(StringBuilder sb, IReadOnlyList<RunRecord> runs)
    {
        var maxTotal = Math.Max(1, runs.Max(static r => r.Counts.Passed + r.Counts.Failed + r.Counts.Skipped + r.Counts.Cancelled));
        var plotWidth = ChartWidth - PadLeft - PadRight;
        var plotHeight = ChartHeight - PadTop - PadBottom;
        var slot = plotWidth / (double)runs.Count;
        var barWidth = Math.Min(28, Math.Max(2, slot * 0.7));

        OpenChart(sb, "Results per run", "Stacked test results for each run");
        AppendYAxis(sb, maxTotal.ToString(CultureInfo.InvariantCulture), "0");

        for (var i = 0; i < runs.Count; i++)
        {
            var counts = runs[i].Counts;
            var x = PadLeft + slot * i + (slot - barWidth) / 2;
            var y = (double)(ChartHeight - PadBottom);
            sb.Append("<g><title>").Append(Encode(RunLabel(runs[i]) + $" · {counts.Passed} passed, {counts.Failed} failed, {counts.Skipped + counts.Cancelled} skipped"))
              .Append("</title>");
            foreach (var (count, css) in new[] { (counts.Passed, "pass"), (counts.Failed, "fail"), (counts.Skipped + counts.Cancelled, "skip") })
            {
                if (count == 0)
                {
                    continue;
                }

                var height = plotHeight * count / (double)maxTotal;
                y -= height;
                sb.Append("<rect class=\"").Append(css).Append("\" x=\"").Append(Num(x)).Append("\" y=\"").Append(Num(y))
                  .Append("\" width=\"").Append(Num(barWidth)).Append("\" height=\"").Append(Num(height)).Append("\"/>");
            }
            sb.Append("</g>\n");
        }

        AppendXAxis(sb, runs, i => PadLeft + slot * i + slot / 2);
        sb.Append("</svg>\n<div class=\"legend\"><span><i class=\"pass\"></i>Passed</span><span><i class=\"fail\"></i>Failed</span><span><i class=\"skip\"></i>Skipped</span></div>\n</section>\n");
    }

    private static void AppendDurationChart(StringBuilder sb, IReadOnlyList<RunRecord> runs)
    {
        var max = Math.Max(1, runs.Max(static r => r.DurationMs));
        var plotWidth = ChartWidth - PadLeft - PadRight;
        var plotHeight = ChartHeight - PadTop - PadBottom;
        double X(int i) => PadLeft + (runs.Count == 1 ? plotWidth / 2.0 : plotWidth * i / (double)(runs.Count - 1));
        double Y(double value) => PadTop + plotHeight - plotHeight * value / max;

        OpenChart(sb, "Duration per run", "Total duration of each run");
        AppendYAxis(sb, TrendFormat.Duration(max), "0");

        if (runs.Count > 1)
        {
            var line = new StringBuilder();
            for (var i = 0; i < runs.Count; i++)
            {
                line.Append(Num(X(i))).Append(',').Append(Num(Y(runs[i].DurationMs))).Append(' ');
            }

            var baseline = Num(ChartHeight - PadBottom);
            sb.Append("<polygon class=\"area\" points=\"").Append(Num(X(0))).Append(',').Append(baseline).Append(' ')
              .Append(line).Append(Num(X(runs.Count - 1))).Append(',').Append(baseline).Append("\"/>\n")
              .Append("<polyline class=\"line\" points=\"").Append(line).Append("\"/>\n");
        }

        for (var i = 0; i < runs.Count; i++)
        {
            sb.Append("<circle class=\"point\" cx=\"").Append(Num(X(i))).Append("\" cy=\"").Append(Num(Y(runs[i].DurationMs)))
              .Append("\" r=\"3.5\"><title>").Append(Encode(RunLabel(runs[i]) + " · " + TrendFormat.Duration(runs[i].DurationMs)))
              .Append("</title></circle>\n");
        }

        AppendXAxis(sb, runs, X);
        sb.Append("</svg>\n</section>\n");
    }

    private static void OpenChart(StringBuilder sb, string title, string description)
        => sb.Append("<section class=\"card\">\n<h2>").Append(Encode(title)).Append("</h2>\n")
             .Append("<svg viewBox=\"0 0 ").Append(ChartWidth).Append(' ').Append(ChartHeight)
             .Append("\" role=\"img\" aria-label=\"").Append(Encode(description)).Append("\">\n");

    private static void AppendYAxis(StringBuilder sb, string maxLabel, string minLabel)
    {
        var bottom = ChartHeight - PadBottom;
        sb.Append("<line class=\"grid\" x1=\"").Append(PadLeft).Append("\" y1=\"").Append(PadTop)
          .Append("\" x2=\"").Append(ChartWidth - PadRight).Append("\" y2=\"").Append(PadTop).Append("\"/>\n")
          .Append("<line class=\"axis\" x1=\"").Append(PadLeft).Append("\" y1=\"").Append(bottom)
          .Append("\" x2=\"").Append(ChartWidth - PadRight).Append("\" y2=\"").Append(bottom).Append("\"/>\n")
          .Append("<text class=\"tick\" text-anchor=\"end\" x=\"").Append(PadLeft - 8).Append("\" y=\"").Append(PadTop + 4).Append("\">")
          .Append(Encode(maxLabel)).Append("</text>\n")
          .Append("<text class=\"tick\" text-anchor=\"end\" x=\"").Append(PadLeft - 8).Append("\" y=\"").Append(bottom + 4).Append("\">")
          .Append(Encode(minLabel)).Append("</text>\n");
    }

    // Label the first, middle and last runs; more labels would collide on long histories.
    private static void AppendXAxis(StringBuilder sb, IReadOnlyList<RunRecord> runs, Func<int, double> x)
    {
        var indices = new SortedSet<int> { 0, runs.Count / 2, runs.Count - 1 };
        foreach (var i in indices)
        {
            var anchor = runs.Count == 1 ? "middle" : i == 0 ? "start" : i == runs.Count - 1 ? "end" : "middle";
            sb.Append("<text class=\"tick\" text-anchor=\"").Append(anchor).Append("\" x=\"").Append(Num(x(i)))
              .Append("\" y=\"").Append(ChartHeight - 6).Append("\">").Append(Encode(TrendFormat.ShortDate(runs[i].Timestamp)))
              .Append("</text>\n");
        }
    }

    private static void AppendTestSections(StringBuilder sb, RenderContext context)
    {
        var report = context.Report;
        sb.Append("<div class=\"legend dots\">Recent results, oldest first:")
          .Append("<span><span class=\"r pass\"></span>Passed</span><span><span class=\"r retry\"></span>Passed after retry</span>")
          .Append("<span><span class=\"r fail\"></span>Failed</span><span><span class=\"r skip\"></span>Skipped</span></div>\n");

        AppendTestTable(sb, context, "Newly failing", "Failed in the latest run after passing before.",
            report.NewlyFailing(), "Failures", static t => $"{t.Failures} of {t.Runs}");

        AppendTestTable(sb, context, "Flaky tests", "Had one-off failures (or passes) between opposite outcomes, or passed only after a retry.",
            report.Flakiest(TableRows), "Why", TrendsMarkdownGenerator.FlakinessDetail, numeric: false);

        AppendTestTable(sb, context, "Slowing down",
            $"At least {TrendFormat.Ratio(TrendReport.SlowdownRatio)} slower in the latest run than their median over earlier runs.",
            report.SlowingDown(TableRows), "Latest vs usual",
            static t => $"{TrendFormat.Duration(t.LastDurationMs!.Value)} vs {TrendFormat.Duration(t.BaselineDurationMs!.Value)} ({TrendFormat.Ratio(t.Slowdown!.Value)})");

        AppendTestTable(sb, context, "Most failing tests", "Ranked by failures across the analyzed runs.",
            report.MostFailing(TableRows), "Failures", static t => $"{t.Failures} of {t.Runs} ({TrendFormat.Percent(t.FailureRate)})");

        AppendTestTable(sb, context, "Slowest tests", "Ranked by median duration.",
            report.Slowest(TableRows), "Median", static t => TrendFormat.Duration(t.MedianDurationMs));
    }

    private static void AppendTestTable(StringBuilder sb, RenderContext context, string title, string description,
        IReadOnlyList<TestTrend> tests, string valueHeader, Func<TestTrend, string> value, bool numeric = true)
    {
        sb.Append("<section class=\"card\">\n<h2>").Append(Encode(title));
        if (tests.Count > 0)
        {
            sb.Append(" <span class=\"count\">").Append(tests.Count).Append("</span>");
        }
        sb.Append("</h2>\n<p class=\"muted\">").Append(Encode(description)).Append("</p>\n");

        if (tests.Count == 0)
        {
            sb.Append("<p class=\"empty\">None.</p>\n</section>\n");
            return;
        }

        var valueClass = numeric ? "num" : "detail";
        sb.Append("<div class=\"scroll\"><table>\n<thead><tr><th>Test</th><th>Recent results</th><th class=\"").Append(valueClass).Append("\">")
          .Append(Encode(valueHeader)).Append("</th></tr></thead>\n<tbody>\n");
        foreach (var test in tests)
        {
            sb.Append("<tr><td class=\"name\">").Append(Encode(test.Name));
            if (context.ShowSuites)
            {
                sb.Append("<div class=\"suite\">").Append(Encode(test.Suite)).Append("</div>");
            }
            sb.Append("</td><td class=\"results\">");
            AppendResultDots(sb, test.RecentResults);
            sb.Append("</td><td class=\"").Append(valueClass).Append("\">").Append(Encode(value(test))).Append("</td></tr>\n");
        }
        sb.Append("</tbody>\n</table></div>\n</section>\n");
    }

    private static void AppendResultDots(StringBuilder sb, IReadOnlyList<TestResultPoint> results)
    {
        foreach (var result in results)
        {
            var css = result.Status switch
            {
                TestRunStatus.Passed when result.PassedAfterRetry => "retry",
                TestRunStatus.Passed => "pass",
                TestRunStatus.Failed => "fail",
                _ => "skip",
            };
            sb.Append("<span class=\"r ").Append(css).Append("\" title=\"")
              .Append(Encode($"{TrendFormat.Date(result.Timestamp)} · {TrendFormat.StatusName(result)} · {TrendFormat.Duration(result.DurationMs)}"))
              .Append("\"></span>");
        }
    }

    private static void AppendRecentRuns(StringBuilder sb, IReadOnlyList<RunRecord> runs, RenderContext context)
    {
        sb.Append("<section class=\"card\">\n<h2>Recent runs</h2>\n<div class=\"scroll\"><table>\n<thead><tr><th>When</th><th>Commit</th><th>Branch</th>");
        if (context.ShowSuites)
        {
            sb.Append("<th>Suite</th>");
        }
        sb.Append("<th class=\"num\">Passed</th><th class=\"num\">Failed</th><th class=\"num\">Skipped</th><th class=\"num\">Pass rate</th><th class=\"num\">Duration</th></tr></thead>\n<tbody>\n");

        foreach (var run in runs.Reverse().Take(TableRows))
        {
            var c = run.Counts;
            sb.Append("<tr><td>").Append(Encode(TrendFormat.Date(run.Timestamp))).Append("</td><td>");
            AppendCommit(sb, run);
            sb.Append("</td><td>").Append(Encode(run.Branch ?? "")).Append("</td>");
            if (context.ShowSuites)
            {
                sb.Append("<td>").Append(Encode(run.Suite)).Append("</td>");
            }
            sb.Append("<td class=\"num\">").Append(c.Passed).Append("</td><td class=\"num").Append(c.Failed > 0 ? " bad" : "").Append("\">").Append(c.Failed)
              .Append("</td><td class=\"num\">").Append(c.Skipped + c.Cancelled)
              .Append("</td><td class=\"num\">").Append(Encode(c.PassRate is { } rate ? TrendFormat.Percent(rate) : "n/a"))
              .Append("</td><td class=\"num\">").Append(Encode(TrendFormat.Duration(run.DurationMs))).Append("</td></tr>\n");
        }

        sb.Append("</tbody>\n</table></div>\n</section>\n");
    }

    private static void AppendCommit(StringBuilder sb, RunRecord run)
    {
        if (run.CommitSha is not { } sha)
        {
            return;
        }

        var text = Encode(TrendFormat.ShortSha(sha));
        if (IsWebUrl(run.CommitUrl))
        {
            sb.Append("<a href=\"").Append(Encode(run.CommitUrl!)).Append("\"><code>").Append(text).Append("</code></a>");
        }
        else
        {
            sb.Append("<code>").Append(text).Append("</code>");
        }
    }

    // The history file is plain JSON anyone can edit; never turn a non-web URL into a link.
    private static bool IsWebUrl(string? url)
        => url is not null
           && (url.StartsWith("https://", StringComparison.OrdinalIgnoreCase) || url.StartsWith("http://", StringComparison.OrdinalIgnoreCase));

    private static string RunLabel(RunRecord run)
        => TrendFormat.Date(run.Timestamp) + (run.CommitSha is { } sha ? " · " + TrendFormat.ShortSha(sha) : "");

    private static string Encode(string value) => WebUtility.HtmlEncode(value);

    private static string Num(double value) => value.ToString("0.#", CultureInfo.InvariantCulture);

